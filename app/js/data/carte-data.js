/** Inverse l'ordre des points d'un segment [lon, lat, lon, lat…]. */
function rev(seg) {
  const out = [];
  for (let i = seg.length - 2; i >= 0; i -= 2) out.push(seg[i], seg[i + 1]);
  return out;
}

/** Met des segments bout à bout (le dernier point d'un segment est le premier du suivant). */
function chain(...segs) {
  const out = [];
  for (const seg of segs) {
    const n = out.length;
    // les segments se suivent : sinon, une frontière est à l'envers (erreur de saisie)
    if (n && (out[n - 2] !== seg[0] || out[n - 1] !== seg[1])) throw new Error(`carte : segments disjoints en ${out.slice(-2)} / ${seg.slice(0, 2)}`);
    for (let i = 0; i < seg.length; i += 2) {
      const n = out.length;
      if (n && out[n - 2] === seg[i] && out[n - 1] === seg[i + 1]) continue;
      out.push(seg[i], seg[i + 1]);
    }
  }
  return out;
}

/** Un contour fait de segments : il doit revenir à son point de départ (qui n'est pas répété). */
function ring(...segs) {
  const out = chain(...segs);
  const n = out.length;
  if (out[0] !== out[n - 2] || out[1] !== out[n - 1]) throw new Error(`carte : contour ouvert en ${out.slice(0, 2)} / ${out.slice(-2)}`);
  out.length = n - 2;
  return out;
}

