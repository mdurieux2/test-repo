/** Le contour [lon, lat…] → liste de points [x, y] de la carte. */
export function projectRing(r) {
  const pts = [];
  for (let i = 0; i < r.length; i += 2) pts.push(toXY(r[i], r[i + 1]));
  return pts;
}

/** Le tracé SVG d'une liste de contours (coordonnées arrondies au centième). */
export function pathOf(rings) {
  return rings.map((r) => `M${projectRing(r).map(([x, y]) => `${+x.toFixed(2)} ${+y.toFixed(2)}`).join('L')}Z`).join('');
}

/** Le point (lon, lat) est-il dans l'un des contours (règle pair-impair, contour par contour) ? */
export function inRings(rings, lon, lat) {
  const [x, y] = toXY(lon, lat);
  return rings.some((r) => {
    const pts = projectRing(r);
    let inside = false;
    for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
      const [xi, yi] = pts[i];
      const [xj, yj] = pts[j];
      if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
    return inside;
  });
}

/** Le rectangle [x0, y0, x1, y1] des contours, limité à la vue (ce que l'enfant voit). */
export function boundsIn(view, rings) {
  const [bx, by, bw, bh] = VIEWS[view].box;
  let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity];
  for (const r of rings) {
    for (const [x, y] of projectRing(r)) {
      const cx = Math.min(Math.max(x, bx), bx + bw);
      const cy = Math.min(Math.max(y, by), by + bh);
      [x0, y0, x1, y1] = [Math.min(x0, cx), Math.min(y0, cy), Math.max(x1, cx), Math.max(y1, cy)];
    }
  }
  return [x0, y0, x1, y1];
}

/** Taille d'une zone sur une vue : celle de sa plus grande partie (moyenne de la largeur et de la hauteur visibles). */
export function sizeIn(view, rings) {
  return Math.max(...rings.map((r) => {
    const [x0, y0, x1, y1] = boundsIn(view, [r]);
    return Math.sqrt(Math.max(0, x1 - x0) * Math.max(0, y1 - y0));
  }));
}

/**
 * Le point touchable d'un pays sur une vue, s'il est trop petit pour un doigt (sinon null) :
 * [x, y, rayon] en coordonnées de la carte.
 */
export function dotFor(view, id) {
  const c = COUNTRIES[id];
  const { min, dot } = VIEWS[view];
  if (sizeIn(view, c.rings) >= min) return null;
  const [lon, lat] = c.dot || c.at;
  return [...toXY(lon, lat), dot];
}

/** Tracés d'une vue, calculés une fois : continents, pays, océans, mers, en chemins SVG. */
const cache = {};
export function mapPaths(view) {
  if (cache[view]) return cache[view];
  const of = (table) => Object.fromEntries(Object.entries(table).map(([id, z]) => [id, pathOf(z.rings)]));
  cache[view] = {
    box: VIEWS[view].box,
    continents: of(CONTINENTS),
    countries: of(COUNTRIES),
    oceans: of(OCEANS),
    seas: of(SEAS),
  };
  return cache[view];
}

/** Où écrire le nom d'un pays sur une vue (la Russie a un autre point sur la carte d'Europe). */
export function atIn(view, id) {
  const c = COUNTRIES[id];
  return (view === 'europe' && c.atEurope) || c.at;
}

/** Le nom de n'importe quelle zone de la carte (pays, continent, océan, mer, capitale). */
export function zoneName(id) {
  if (id.startsWith('cap-')) return COUNTRIES[id.slice(4)].capital[0];
  return (COUNTRIES[id] || CONTINENTS[id] || OCEANS[id] || SEAS[id])?.name;
}
