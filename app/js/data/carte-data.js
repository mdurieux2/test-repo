// La carte du monde du jeu « La carte du monde » : contours simplifiés des continents, des océans
// et d'une sélection de pays, écrits à la main dans ce fichier (longitude, latitude en degrés).
//
// Les frontières communes à deux pays sont écrites une seule fois (segments nommés) puis
// réutilisées par les deux pays : les pays voisins se touchent exactement, sans trou ni
// chevauchement. Projection de Miller (comme beaucoup de cartes murales) : x = longitude,
// y = latitude « étirée » vers les pôles. Deux vues : le monde entier, et l'Europe agrandie.

const RAD = Math.PI / 180;

/** Ordonnée de Miller (en « degrés ») d'une latitude. */
export function millerY(lat) {
  return (1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * lat * RAD))) / RAD;
}

/** Point [longitude, latitude] → point de la carte [x, y] (y vers le bas, comme en SVG). */
export function toXY(lon, lat) {
  return [lon, -millerY(lat)];
}

/** Les deux cartes : le monde, et l'Europe agrandie (avec le nord du Maroc). */
export const VIEWS = {
  monde: { lon: [-180, 180], lat: [84, -78], label: 11, dot: 11, min: 22, title: 'Le monde' },
  europe: { lon: [-12, 31], lat: [63, 32], label: 1.5, dot: 2, min: 3.6, title: 'L’Europe' },
};
for (const view of Object.values(VIEWS)) {
  const [x0, y0] = toXY(view.lon[0], view.lat[0]);
  const [x1, y1] = toXY(view.lon[1], view.lat[1]);
  view.box = [x0, y0, x1 - x0, y1 - y0];
}

